def build(events: list[Event] | None = None) -> None:
    ensure_dirs()
    _write_logos()
    weights = load_weights()
    if SOURCE_SCOREBOARD_PATH.exists():
        with open(SOURCE_SCOREBOARD_PATH) as f:
            scoreboard = json.load(f)
    else:
        scoreboard = {"sources": {}, "n_events": 0, "window": {}, "bankroll_curve": []}
    events = events or []
    env = _env()
    (DOCS_DIR / "index.html").write_text(render_index(env, events, weights))
    render_event_pages(env, events, weights)
    (DOCS_DIR / "source-scoreboard.html").write_text(render_sources(env, scoreboard, weights))
    (DOCS_DIR / "methodology.html").write_text(render_methodology(env))
    (DOCS_DIR / "backtest.html").write_text(render_backtest(env, scoreboard))
    write_source_scoreboard_md(scoreboard, DOCS_DIR / "source-scoreboard.md")
    log.info("Site built → %s", DOCS_DIR)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s %(message)s")
    build()
