def _slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "event"


def _layout(env: Environment, page_title: str, active: str, content_html: str, asset_root: str = "") -> str:
    layout = env.get_template("_layout.html")
    return layout.render(
        page_title=page_title,
        active=active,
        content=content_html,
        asset_root=asset_root,
        updated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
    )


def _market_devigged_home_prob(ev: Event) -> float | None:
    home_prices = [
        american_to_prob(ln.american) for ln in ev.lines if ln.side == "home" and not ln.is_opening
    ]
    away_prices = [
        american_to_prob(ln.american) for ln in ev.lines if ln.side == "away" and not ln.is_opening
    ]
    if not home_prices or not away_prices:
        return None
    h = sum(home_prices) / len(home_prices)
    a = sum(away_prices) / len(away_prices)
    h_devig, _ = devig_two_way(h, a)
    return h_devig


def _badge_blocks(signals: list[str]) -> list[dict]:
    out: list[dict] = []
    for sig in signals:
        if sig in BADGE_LABELS:
            label, cls = BADGE_LABELS[sig]
            out.append({"label": label, "cls": cls})
    return out


def _pick_price(ev: Event) -> int | None:
    if ev.pick is None:
        return None
    prices = [ln.american for ln in ev.lines if ln.side == ev.pick and not ln.is_opening]
    if not prices:
        prices = [ln.american for ln in ev.lines if ln.side == ev.pick]
    if not prices:
        return None
    return int(round(sum(prices) / len(prices)))


def _expected_profit(ev: Event, price: int | None) -> float | None:
    if price is None or ev.pick_prob is None:
        return None
    win_profit = american_to_profit(price, FLAT_STAKE)
    return ev.pick_prob * win_profit - (1 - ev.pick_prob) * FLAT_STAKE


def _event_view(ev: Event, weights: dict[str, float]) -> dict:
    market_p = _market_devigged_home_prob(ev)
    price = _pick_price(ev)
    ep = _expected_profit(ev, price)
    badges = _badge_blocks(ev.signals)
    return {
        "raw": ev,
        "slug": _slugify(f"{ev.commence_time.strftime('%Y-%m-%d')}-{ev.away}-at-{ev.home}-{ev.event_id[-6:]}"),
        "sport_upper": ev.sport.upper(),
        "commence_str": ev.commence_time.strftime("%a %b %d · %H:%M UTC"),
        "n_sources": len(ev.source_probs),
        "pick_label": (ev.home if ev.pick == "home" else ev.away).upper() if ev.pick else "—",
        "pick_prob": ev.pick_prob or 0.0,
        "pick_price_str": _american_str(price) if price is not None else "—",
        "expected_profit": ep,
        "expected_profit_str": f"${ep:+.0f}" if ep is not None else "—",
        "blended_home_prob": ev.blended_home_prob or 0.0,
        "market_home_str": f"{market_p:.1%}" if market_p is not None else "—",
        "badges": badges,
        "home": ev.home,
        "away": ev.away,
    }


def _american_str(price: int) -> str:
    return f"{price:+d}"


def _build_event_page_view(ev: Event, weights: dict[str, float]) -> dict:
    view = _event_view(ev, weights)
    src_names = [p.source for p in ev.source_probs]
    w_norm = _resolve_weights(src_names, weights) if src_names else {}
    source_rows = []
    for sp in ev.source_probs:
        source_rows.append(
            {
                "source": sp.source,
                "prob": sp.home_win_prob,
                "weight": w_norm.get(sp.source, 0.0),
                "captured": sp.captured_at.strftime("%Y-%m-%d %H:%M"),
            }
        )
    lines = []
    for ln in ev.lines:
        lines.append(
            {
                "book": ln.book,
                "side_label": ev.home if ln.side == "home" else ev.away,
                "american_str": _american_str(ln.american),
                "implied": american_to_prob(ln.american),
                "kind": "OPEN" if ln.is_opening else "CLOSE",
            }
        )
    signal_explanation = " ".join(
        SIGNAL_EXPLAIN.get(s, "") for s in ev.signals if s in SIGNAL_EXPLAIN
    )
    view.update({
        "source_rows": source_rows,
        "lines": lines,
        "signal_explanation": signal_explanation,
    })
    return view


