    xs = [c["predicted"] for c in calibration if c.get("predicted") is not None]
    ys = [c["actual"] for c in calibration if c.get("actual") is not None]
    ns = [c["n"] for c in calibration if c.get("predicted") is not None]
    fig, ax = plt.subplots(figsize=(6, 5), facecolor="#1a1c22")
    ax.set_facecolor("#1a1c22")
    ax.plot([0, 1], [0, 1], color="#8b8d96", lw=0.8, ls="--")
    if xs:
        ax.scatter(xs, ys, s=[max(20, min(400, n * 4)) for n in ns],
                   color="#F58220", edgecolor="#1a1c22", linewidths=1.5, alpha=0.9)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_xlabel("Predicted probability", color="#8b8d96")
    ax.set_ylabel("Realized win rate", color="#8b8d96")
    ax.tick_params(colors="#8b8d96")
